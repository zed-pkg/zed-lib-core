const JSON_SCHEMA_DIALECT = 'https://json-schema.org/draft/2020-12/schema';
const GENERATED_HEADER = 'Generated by tools/schema-shadow-codegen.mjs. DO NOT EDIT.';
const SHADOW_HEADER = 'SHADOW ONLY. Production migration authority remains src/rust-orm/sql/registry.sql.';
const IDENTIFIER = /^[a-z_][a-z0-9_]*$/;
const ENTRY_PATH = fileURLToPath(import.meta.url);
const REPO_ROOT = resolve(dirname(ENTRY_PATH), '..');
const DEFAULT_SCHEMA = resolve(REPO_ROOT, 'schema/persistence.schema.json');
const GENERATED_ROOT = resolve(REPO_ROOT, 'generated/schema-orm-shadow');

function fail(message) {
  throw new Error(message);
}

function assertIdentifier(value, label) {
  if (typeof value !== 'string' || !IDENTIFIER.test(value)) fail(`${label} must be a safe snake_case identifier: ${value}`);
}

function assertOutputRoot(value) {
  const outputRoot = resolve(value);
  if (outputRoot !== GENERATED_ROOT) {
    fail(`refusing to delete or generate outside ${GENERATED_ROOT}`);
  }
  return outputRoot;
}

function stableStringify(value) {
  const sort = (input) => {
    if (Array.isArray(input)) return input.map(sort);
    if (input && typeof input === 'object') {
      return Object.fromEntries(Object.keys(input).sort().map((key) => [key, sort(input[key])]));
    }
    return input;
  };
  return `${JSON.stringify(sort(value), null, 2)}\n`;
}

function sha256(content) {
  return createHash('sha256').update(content).digest('hex');
}

function snakeCase(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[-.\s]+/g, '_')
    .replace(/__+/g, '_')
    .toLowerCase();
}

function pascalCase(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function camelCase(value) {
  const pascal = pascalCase(value);
  return pascal ? pascal.charAt(0).toLowerCase() + pascal.slice(1) : pascal;
}

function goName(value) {
  return pascalCase(value)
    .replace(/Api/g, 'API')
    .replace(/Id(?=$|[A-Z])/g, 'ID')
    .replace(/Ip/g, 'IP')
    .replace(/Sha256/g, 'SHA256')
    .replace(/Url/g, 'URL')
    .replace(/Vcs/g, 'VCS');
}

function rustName(value) {
  const result = snakeCase(value);
  const reserved = new Set(['type', 'match', 'ref', 'self', 'crate', 'super', 'mod', 'use', 'enum', 'struct', 'fn', 'impl', 'async', 'await', 'move', 'where', 'loop', 'in', 'as', 'dyn']);
  return reserved.has(result) ? `r#${result}` : result;
}

function jsonType(property) {
  const values = (Array.isArray(property.type) ? property.type : [property.type]).filter((value) => value !== 'null');
  if (values.length !== 1) fail(`property must have exactly one non-null type: ${JSON.stringify(property)}`);
  return values[0];
}

function normalizeSchema(schema) {
  if (schema.$schema !== JSON_SCHEMA_DIALECT) fail(`schema must use ${JSON_SCHEMA_DIALECT}`);
  const contract = schema['x-lib-core'];
  if (!contract || contract.authorityMode !== 'shadow-import') fail('x-lib-core.authorityMode must remain shadow-import');
  if (contract.productionSql !== 'src/rust-orm/sql/registry.sql') fail('production SQL authority moved unexpectedly');
  if (!String(contract.generatedSql).startsWith('generated/schema-orm-shadow/')) fail('shadow output path is not isolated');
  if (!schema.$defs || typeof schema.$defs !== 'object') fail('schema.$defs is required');

  const entities = [];
  for (const [name, definition] of Object.entries(schema.$defs)) {
    const db = definition['x-db'];
    if (!db?.table) continue;
    assertIdentifier(db.table, `${name}.x-db.table`);
    if (definition.type !== 'object') fail(`${name} must be an object`);
    const required = new Set(definition.required ?? []);
    const fields = Object.entries(definition.properties ?? {}).map(([fieldName, property]) => {
      const fieldDb = property['x-db'] ?? {};
      const column = fieldDb.column ?? snakeCase(fieldName);
      assertIdentifier(column, `${name}.${fieldName}.x-db.column`);
      return {
        name: fieldName,
        rustName: rustName(fieldName),
        goName: goName(fieldName),
        tsName: camelCase(fieldName),
        column,
        property,
        kind: jsonType(property),
        required: required.has(fieldName),
        nullable: !required.has(fieldName) || (Array.isArray(property.type) && property.type.includes('null')),
        db: fieldDb,
        importedSeaOrmType: property['x-import']?.seaOrmType ?? null,
      };
    });
    const columns = fields.map((field) => field.column);
    if (new Set(columns).size !== columns.length) fail(`${name} contains duplicate persistence columns`);
    const fieldMap = new Map(fields.map((field) => [field.name, field]));
    const primaryKey = db.primaryKey ?? (fieldMap.has('id') ? ['id'] : []);
    if (!primaryKey.length) fail(`${name} has no primary key`);
    if (new Set(primaryKey).size !== primaryKey.length) fail(`${name} primary key contains duplicate fields`);
    for (const field of primaryKey) if (!fieldMap.has(field)) fail(`${name} primary key references ${field}`);
    entities.push({
      name,
      className: pascalCase(name),
      module: snakeCase(name),
      table: db.table,
      source: db.source,
      sourceBlobSha: db.sourceBlobSha,
      description: definition.description ?? '',
      interfaceType: definition['x-interface']?.type ?? name,
      fields,
      fieldMap,
      primaryKey,
    });
  }
  if (entities.length !== 17) fail(`expected 17 imported entities, got ${entities.length}`);
  const tables = entities.map((entity) => entity.table);
  if (new Set(tables).size !== tables.length) fail('imported entities contain duplicate table names');
  const entityMap = new Map(entities.map((entity) => [entity.name, entity]));
  for (const entity of entities) {
    for (const field of entity.fields) {
      const reference = field.db.references;
      if (!reference) continue;
      const target = entityMap.get(reference.entity);
      if (!target?.fieldMap.has(reference.field)) fail(`${entity.name}.${field.name} has an invalid reference`);
    }
  }
  return { schema, contract, entities, entityMap };
}

function topologicalEntities(model) {
  const remaining = new Map(model.entities.map((entity) => [entity.name, entity]));
  const result = [];
  while (remaining.size) {
    const ready = [...remaining.values()].filter((entity) =>
      entity.fields.every((field) => !field.db.references || !remaining.has(field.db.references.entity)));
    if (!ready.length) return model.entities;
    ready.sort((left, right) => left.name.localeCompare(right.name));
    for (const entity of ready) {
      result.push(entity);
      remaining.delete(entity.name);
    }
  }
  return result;
}

function postgresType(field) {
  if (field.kind === 'string') {
    if (field.property.format === 'uuid') return 'uuid';
    if (field.property.format === 'date-time') return 'timestamptz';
    return 'text';
  }
  if (field.kind === 'integer') return field.property.format === 'int32' ? 'integer' : 'bigint';
  if (field.kind === 'number') return 'double precision';
  if (field.kind === 'boolean') return 'boolean';
  if (field.kind === 'object' || field.kind === 'array') return 'jsonb';
  fail(`unsupported PostgreSQL type ${field.kind}`);
}

function sqliteType(field) {
  if (field.kind === 'integer' || field.kind === 'boolean') return 'integer';
  if (field.kind === 'number') return 'real';
  return 'text';
}

function generateSql(model, dialect) {
  const lines = [
    `-- ${GENERATED_HEADER}`,
    `-- ${SHADOW_HEADER}`,
    `-- Dialect: ${dialect}`,
    '-- This file is a review artifact, not an executable migration.',
    '',
  ];
  for (const entity of topologicalEntities(model)) {
    lines.push(`-- Imported from ${entity.source} @ ${entity.sourceBlobSha}.`);
    lines.push(`create table if not exists ${entity.table} (`);
    const clauses = entity.fields.map((field) => {
      const type = dialect === 'postgres' ? postgresType(field) : sqliteType(field);
      const values = [`  ${field.column} ${type}`];
      if (!field.nullable) values.push('not null');
      if (field.db.references) {
        const target = model.entityMap.get(field.db.references.entity);
        const targetField = target.fieldMap.get(field.db.references.field);
        values.push(`references ${target.table} (${targetField.column})`);
      }
      return values.join(' ');
    });
    clauses.push(`  primary key (${entity.primaryKey.map((field) => entity.fieldMap.get(field).column).join(', ')})`);
    lines.push(clauses.join(',\n'));
    lines.push(');', '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function rustScalar(field) {
  if (field.kind === 'string') {
    if (field.property.format === 'uuid') return 'Uuid';
    if (field.property.format === 'date-time') return 'DateTimeWithTimeZone';
    return 'String';
  }
  if (field.kind === 'integer') return field.property.format === 'int32' ? 'i32' : 'i64';
  if (field.kind === 'number') return 'f64';
  if (field.kind === 'boolean') return 'bool';
  if (field.kind === 'object' || field.kind === 'array') return 'Json';
  fail(`unsupported Rust type ${field.kind}`);
}

function generateSeaOrm(model) {
  const lines = [
    `// ${GENERATED_HEADER}`,
    `// ${SHADOW_HEADER}`,
    '#![allow(clippy::module_inception)]',
    '',
  ];
  for (const entity of model.entities) {
    const references = entity.fields.filter((field) => field.db.references);
    lines.push(`pub mod ${entity.module} {`, '    use sea_orm::entity::prelude::*;', '');
    lines.push(`    /// Shadow model for \`${entity.table}\`; imported from \`${entity.source}\`.`);
    lines.push('    #[derive(Clone, Debug, PartialEq, DeriveEntityModel)]');
    lines.push(`    #[sea_orm(table_name = "${entity.table}")]`, '    pub struct Model {');
    for (const field of entity.fields) {
      const attributes = [];
      if (entity.primaryKey.includes(field.name)) attributes.push('primary_key', 'auto_increment = false');
      if (field.kind === 'object' || field.kind === 'array') attributes.push('column_type = "JsonBinary"');
      if (attributes.length) lines.push(`        #[sea_orm(${attributes.join(', ')})]`);
      const type = field.nullable ? `Option<${rustScalar(field)}>` : rustScalar(field);
      lines.push(`        pub ${field.rustName}: ${type},`);
    }
    lines.push('    }', '', '    #[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]');
    if (!references.length) {
      lines.push('    pub enum Relation {}', '');
    } else {
      lines.push('    pub enum Relation {');
      for (const field of references) {
        const target = model.entityMap.get(field.db.references.entity);
        const variant = pascalCase(`${target.name}_${field.name}`);
        lines.push('        #[sea_orm(');
        lines.push(`            belongs_to = "super::${target.module}::Entity",`);
        lines.push(`            from = "Column::${pascalCase(field.name)}",`);
        lines.push(`            to = "super::${target.module}::Column::${pascalCase(field.db.references.field)}"`);
        lines.push('        )]');
        lines.push(`        ${variant},`);
      }
      lines.push('    }', '');
      lines.push('    // Multiple foreign keys may point at one entity; use Relation variants explicitly.', '');
    }
    lines.push('    impl ActiveModelBehavior for ActiveModel {}', '}', '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function drizzleBuilder(field) {
  const name = JSON.stringify(field.column);
  if (field.kind === 'string') {
    if (field.property.format === 'uuid') return `uuid(${name})`;
    if (field.property.format === 'date-time') return `timestamp(${name}, { withTimezone: true, mode: 'date' })`;
    return `text(${name})`;
  }
  if (field.kind === 'integer') return field.property.format === 'int32' ? `integer(${name})` : `bigint(${name}, { mode: 'bigint' })`;
  if (field.kind === 'number') return `doublePrecision(${name})`;
  if (field.kind === 'boolean') return `boolean(${name})`;
  if (field.kind === 'object' || field.kind === 'array') return `jsonb(${name})`;
  fail(`unsupported Drizzle type ${field.kind}`);
}

function generateDrizzle(model) {
  const lines = [
    `// ${GENERATED_HEADER}`,
    `// ${SHADOW_HEADER}`,
    `import { pgTable, uuid, text, integer, bigint, boolean, timestamp, jsonb, doublePrecision, primaryKey } from 'drizzle-orm/pg-core';`,
    '',
  ];
  // Prefix every top-level binding so entity names such as `Package` cannot
  // become strict-mode reserved words such as `package` in the emitted ESM.
  const variables = new Map(model.entities.map((entity) => [entity.name, `zed${entity.className}`]));
  for (const entity of topologicalEntities(model)) {
    lines.push(`export const ${variables.get(entity.name)} = pgTable(${JSON.stringify(entity.table)}, {`);
    for (const field of entity.fields) {
      let builder = drizzleBuilder(field);
      if (!field.nullable) builder += '.notNull()';
      if (entity.primaryKey.length === 1 && entity.primaryKey[0] === field.name) builder += '.primaryKey()';
      if (field.db.references) {
        const target = model.entityMap.get(field.db.references.entity);
        const targetField = target.fieldMap.get(field.db.references.field);
        builder += `.references(() => ${variables.get(target.name)}.${targetField.tsName})`;
      }
      lines.push(`  ${field.tsName}: ${builder},`);
    }
    if (entity.primaryKey.length > 1) {
      lines.push(`}, (table) => [primaryKey({ columns: [${entity.primaryKey.map((field) => `table.${entity.fieldMap.get(field).tsName}`).join(', ')}] })]);`, '');
    } else {
      lines.push('});', '');
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function prismaType(field) {
  if (field.kind === 'string') {
    if (field.property.format === 'uuid') return ['String', '@db.Uuid'];
    if (field.property.format === 'date-time') return ['DateTime', '@db.Timestamptz(6)'];
    return ['String', '@db.Text'];
  }
  if (field.kind === 'integer') return [field.property.format === 'int32' ? 'Int' : 'BigInt', ''];
  if (field.kind === 'number') return ['Float', ''];
  if (field.kind === 'boolean') return ['Boolean', ''];
  if (field.kind === 'object' || field.kind === 'array') return ['Json', ''];
  fail(`unsupported Prisma type ${field.kind}`);
}

function generatePrisma(model) {
  const incoming = new Map(model.entities.map((entity) => [entity.name, []]));
  for (const source of model.entities) {
    for (const field of source.fields.filter((field) => field.db.references)) {
      incoming.get(field.db.references.entity).push({ source, field });
    }
  }
  const lines = [
    `// ${GENERATED_HEADER}`,
    `// ${SHADOW_HEADER}`,
    'generator client {',
    '  provider = "prisma-client-js"',
    '}',
    '',
    'datasource db {',
    '  provider = "postgresql"',
    '  url      = env("DATABASE_URL")',
    '}',
    '',
  ];
  for (const entity of model.entities) {
    lines.push(`model ${entity.className} {`);
    for (const field of entity.fields) {
      const [type, native] = prismaType(field);
      const attributes = [];
      if (entity.primaryKey.length === 1 && entity.primaryKey[0] === field.name) attributes.push('@id');
      if (native) attributes.push(native);
      if (field.column !== field.name) attributes.push(`@map(${JSON.stringify(field.column)})`);
      lines.push(`  ${field.tsName} ${type}${field.nullable ? '?' : ''}${attributes.length ? ` ${attributes.join(' ')}` : ''}`);
    }
    for (const field of entity.fields.filter((candidate) => candidate.db.references)) {
      const target = model.entityMap.get(field.db.references.entity);
      const relationName = `${entity.className}_${pascalCase(field.name)}_${target.className}`;
      lines.push(`  ${camelCase(target.name)}By${pascalCase(field.name)} ${target.className}${field.nullable ? '?' : ''} @relation(${JSON.stringify(relationName)}, fields: [${field.tsName}], references: [${target.fieldMap.get(field.db.references.field).tsName}])`);
    }
    for (const relation of incoming.get(entity.name)) {
      const relationName = `${relation.source.className}_${pascalCase(relation.field.name)}_${entity.className}`;
      lines.push(`  ${camelCase(relation.source.name)}By${pascalCase(relation.field.name)} ${relation.source.className}[] @relation(${JSON.stringify(relationName)})`);
    }
    if (entity.primaryKey.length > 1) lines.push(`  @@id([${entity.primaryKey.map((field) => entity.fieldMap.get(field).tsName).join(', ')}])`);
    lines.push(`  @@map(${JSON.stringify(entity.table)})`, '}', '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function typeormType(field) {
  if (field.kind === 'string') {
    if (field.property.format === 'uuid') return ['uuid', 'string'];
    if (field.property.format === 'date-time') return ['timestamptz', 'Date'];
    return ['text', 'string'];
  }
  if (field.kind === 'integer') return [field.property.format === 'int32' ? 'integer' : 'bigint', field.property.format === 'int32' ? 'number' : 'string'];
  if (field.kind === 'number') return ['double precision', 'number'];
  if (field.kind === 'boolean') return ['boolean', 'boolean'];
  if (field.kind === 'object') return ['jsonb', 'Record<string, unknown>'];
  if (field.kind === 'array') return ['jsonb', 'unknown[]'];
  fail(`unsupported TypeORM type ${field.kind}`);
}

function generateTypeOrm(model) {
  const lines = [
    `// ${GENERATED_HEADER}`,
    `// ${SHADOW_HEADER}`,
    `import { Column, Entity, JoinColumn, ManyToOne, PrimaryColumn } from 'typeorm';`,
    '',
  ];
  for (const entity of model.entities) {
    lines.push(`@Entity(${JSON.stringify(entity.table)})`, `export class ${entity.className} {`);
    for (const field of entity.fields) {
      const [dbType, tsType] = typeormType(field);
      const options = [`name: ${JSON.stringify(field.column)}`, `type: ${JSON.stringify(dbType)}`];
      if (field.nullable) options.push('nullable: true');
      const decorator = entity.primaryKey.includes(field.name) ? 'PrimaryColumn' : 'Column';
      lines.push(`  @${decorator}({ ${options.join(', ')} })`);
      lines.push(`  ${field.tsName}${field.nullable ? '?' : '!'}: ${tsType};`, '');
      if (field.db.references) {
        const target = model.entityMap.get(field.db.references.entity);
        lines.push(`  @ManyToOne(() => ${target.className}, { nullable: ${field.nullable} })`);
        lines.push(`  @JoinColumn({ name: ${JSON.stringify(field.column)}, referencedColumnName: ${JSON.stringify(target.fieldMap.get(field.db.references.field).tsName)} })`);
        lines.push(`  ${camelCase(target.name)}By${pascalCase(field.name)}${field.nullable ? '?' : '!'}: ${target.className};`, '');
      }
    }
    lines.push('}', '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function goScalar(field) {
  if (field.kind === 'string') {
    if (field.property.format === 'uuid') return 'uuid.UUID';
    if (field.property.format === 'date-time') return 'time.Time';
    return 'string';
  }
  if (field.kind === 'integer') return field.property.format === 'int32' ? 'int32' : 'int64';
  if (field.kind === 'number') return 'float64';
  if (field.kind === 'boolean') return 'bool';
  if (field.kind === 'object' || field.kind === 'array') return 'json.RawMessage';
  fail(`unsupported Go type ${field.kind}`);
}

function formatGo(content) {
  const result = spawnSync('gofmt', [], { input: content, encoding: 'utf8' });
  if (result.error?.code === 'ENOENT') fail('gofmt is required');
  if (result.status !== 0) fail(`gofmt failed: ${result.stderr || result.error || 'unknown error'}`);
  return result.stdout;
}

function generateGorm(model) {
  const lines = [
    `// ${GENERATED_HEADER}`,
    `// ${SHADOW_HEADER}`,
    'package models',
    '',
    'import (',
    '\t"encoding/json"',
    '\t"time"',
    '',
    '\t"github.com/google/uuid"',
    ')',
    '',
  ];
  for (const entity of model.entities) {
    lines.push(`type ${entity.className} struct {`);
    for (const field of entity.fields) {
      let type = goScalar(field);
      if (field.nullable) type = `*${type}`;
      const tags = [`column:${field.column}`, `type:${postgresType(field)}`];
      if (entity.primaryKey.includes(field.name)) tags.push('primaryKey', 'autoIncrement:false');
      if (!field.nullable) tags.push('not null');
      lines.push(`\t${field.goName} ${type} \`json:"${field.name}" gorm:"${tags.join(';')}"\``);
    }
    for (const field of entity.fields.filter((candidate) => candidate.db.references)) {
      const target = model.entityMap.get(field.db.references.entity);
      lines.push(`\t${target.className}By${field.goName} ${field.nullable ? '*' : ''}${target.className} \`json:"-" gorm:"foreignKey:${field.goName};references:${target.fieldMap.get(field.db.references.field).goName}"\``);
    }
    lines.push('}', '', `func (${entity.className}) TableName() string { return ${JSON.stringify(entity.table)} }`, '');
  }
  return formatGo(`${lines.join('\n').trimEnd()}\n`);
}

function entField(field) {
  const name = JSON.stringify(field.column);
  let value;
  if (field.kind === 'string') {
    if (field.property.format === 'uuid') value = `field.UUID(${name}, uuid.UUID{})`;
    else if (field.property.format === 'date-time') value = `field.Time(${name})`;
    else value = `field.String(${name})`;
  } else if (field.kind === 'integer') value = field.property.format === 'int32' ? `field.Int32(${name})` : `field.Int64(${name})`;
  else if (field.kind === 'number') value = `field.Float(${name})`;
  else if (field.kind === 'boolean') value = `field.Bool(${name})`;
  else if (field.kind === 'object' || field.kind === 'array') value = `field.JSON(${name}, json.RawMessage{})`;
  else fail(`unsupported Ent type ${field.kind}`);
  if (field.nullable) value += '.Optional().Nillable()';
  value += `.StructTag(${JSON.stringify(`json:"${field.name},omitempty"` )})`;
  if (field.db.references) value += `.Comment(${JSON.stringify(`Foreign key to ${field.db.references.entity}.${field.db.references.field}; production DDL remains SQL-owned.`)})`;
  return value;
}

function generateEnt(model) {
  const lines = [
    `// ${GENERATED_HEADER}`,
    `// ${SHADOW_HEADER}`,
    'package schema',
    '',
    'import (',
    '\t"encoding/json"',
    '\t"time"',
    '',
    '\t"github.com/google/uuid"',
    '',
    '\t"entgo.io/ent"',
    '\t"entgo.io/ent/dialect/entsql"',
    '\tentschema "entgo.io/ent/schema"',
    '\t"entgo.io/ent/schema/field"',
    ')',
    '',
    'var _ = time.Time{}',
    '',
  ];
  for (const entity of model.entities) {
    const writableShape = entity.primaryKey.length === 1 && entity.primaryKey[0] === 'id';
    lines.push(`type ${entity.className} struct {`, `\tent.${writableShape ? 'Schema' : 'View'}`, '}', '');
    lines.push(`func (${entity.className}) Annotations() []entschema.Annotation {`);
    lines.push('\treturn []entschema.Annotation{');
    lines.push(`\t\tentsql.Annotation{Table: ${JSON.stringify(entity.table)}},`);
    if (writableShape) lines.push('\t\tentsql.Skip(),');
    lines.push('\t}', '}', '');
    lines.push(`func (${entity.className}) Fields() []ent.Field {`, '\treturn []ent.Field{');
    for (const field of entity.fields) lines.push(`\t\t${entField(field)},`);
    lines.push('\t}', '}', '');
  }
  return formatGo(`${lines.join('\n').trimEnd()}\n`);
}

function driftBuilder(field) {
  if (field.kind === 'string') return field.property.format === 'date-time' ? 'dateTime()' : 'text()';
  if (field.kind === 'integer') return field.property.format === 'int64' ? 'int64()' : 'integer()';
  if (field.kind === 'number') return 'real()';
  if (field.kind === 'boolean') return 'boolean()';
  if (field.kind === 'object' || field.kind === 'array') return 'text()';
  fail(`unsupported Drift type ${field.kind}`);
}

function driftColumnClass(field) {
  if (field.kind === 'string') return field.property.format === 'date-time' ? 'DateTimeColumn' : 'TextColumn';
  if (field.kind === 'integer') return field.property.format === 'int64' ? 'BigIntColumn' : 'IntColumn';
  if (field.kind === 'number') return 'RealColumn';
  if (field.kind === 'boolean') return 'BoolColumn';
  return 'TextColumn';
}

function generateDrift(model) {
  const lines = [
    `// ${GENERATED_HEADER}`,
    `// ${SHADOW_HEADER}`,
    `import 'package:drift/drift.dart';`,
    '',
  ];
  for (const entity of model.entities) {
    lines.push(`class ${entity.className} extends Table {`);
    lines.push('  @override');
    lines.push(`  String get tableName => ${JSON.stringify(entity.table)};`, '');
    for (const field of entity.fields) {
      let builder = `${driftBuilder(field)}.named(${JSON.stringify(field.column)})`;
      if (field.nullable) builder += '.nullable()';
      lines.push(`  ${driftColumnClass(field)} get ${field.tsName} => ${builder}();`);
    }
    lines.push('', '  @override');
    lines.push(`  Set<Column<Object>> get primaryKey => {${entity.primaryKey.map((field) => entity.fieldMap.get(field).tsName).join(', ')}};`);
    lines.push('}', '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function stormberryType(field) {
  if (field.kind === 'string') return field.property.format === 'date-time' ? 'DateTime' : 'String';
  if (field.kind === 'integer') return 'int';
  if (field.kind === 'number') return 'double';
  if (field.kind === 'boolean') return 'bool';
  if (field.kind === 'object') return 'Map<String, dynamic>';
  if (field.kind === 'array') return 'List<dynamic>';
  fail(`unsupported Stormberry type ${field.kind}`);
}

function generateStormberry(model) {
  const lines = [
    `// ${GENERATED_HEADER}`,
    `// ${SHADOW_HEADER}`,
    `import 'package:stormberry/stormberry.dart';`,
    '',
    `part 'models.schema.dart';`,
    '',
  ];
  for (const entity of model.entities) {
    lines.push(`@Model(tableName: ${JSON.stringify(entity.table)})`);
    lines.push(`abstract class ${entity.className} {`);
    for (const field of entity.fields) {
      if (entity.primaryKey.includes(field.name)) lines.push('  @PrimaryKey()');
      lines.push(`  ${stormberryType(field)}${field.nullable ? '?' : ''} get ${field.tsName};`, '');
    }
    lines.push('}', '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function descriptorData(model) {
  return model.entities.map((entity) => ({
    entity: entity.name,
    interfaceType: entity.interfaceType,
    table: entity.table,
    primaryKey: entity.primaryKey,
    requiredFields: entity.fields.filter((field) => field.required).map((field) => field.name),
  }));
}

function generateSharedTs(model) {
  return `// ${GENERATED_HEADER}\n// ${SHADOW_HEADER}\n\nexport const entityDescriptors = ${stableStringify(descriptorData(model)).trim()} as const;\n\nexport function stableEntityKey(entity: string, record: Readonly<Record<string, unknown>>): string {\n  const descriptor = entityDescriptors.find((candidate) => candidate.entity === entity);\n  if (!descriptor) throw new Error(\`unknown entity: \${entity}\`);\n  return [entity, ...descriptor.primaryKey.map((field) => {\n    const value = record[field];\n    if (value === null || value === undefined || value === '') throw new Error(\`missing primary key field \${entity}.\${field}\`);\n    return encodeURIComponent(String(value));\n  })].join(':');\n}\n`;
}

function generateSharedRust(model) {
  const lines = [
    `// ${GENERATED_HEADER}`,
    `// ${SHADOW_HEADER}`,
    '',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub struct EntityDescriptor {',
    "    pub entity: &'static str,",
    "    pub interface_type: &'static str,",
    "    pub table: &'static str,",
    "    pub primary_key: &'static [&'static str],",
    '}',
    '',
    'pub const ENTITY_DESCRIPTORS: &[EntityDescriptor] = &[',
  ];
  for (const item of descriptorData(model)) {
    lines.push('    EntityDescriptor {');
    lines.push(`        entity: ${JSON.stringify(item.entity)},`);
    lines.push(`        interface_type: ${JSON.stringify(item.interfaceType)},`);
    lines.push(`        table: ${JSON.stringify(item.table)},`);
    lines.push(`        primary_key: &[${item.primaryKey.map((value) => JSON.stringify(value)).join(', ')}],`);
    lines.push('    },');
  }
  lines.push('];');
  return `${lines.join('\n')}\n`;
}

